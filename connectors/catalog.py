"""Ready-made process connector catalog (the Celonis process-connector equivalent).

Each connector = one source system + business process: the tables to extract, the key
columns per table, and how well the modelling agent's priors cover it today:

  full      — the agent drafts the complete event-log mapping from these tables
  partial   — the agent recognizes a subset of the events (noted per connector)
  template  — guided extraction only for now: export the tables and the agent will
              propose what it can from column analysis; dedicated priors are roadmap

This mirrors what a Celonis process connector installs (extractions + transformations +
data model), with our §1.1 twist: the transformation/data-model part is generated by the
agent and confirmed by a human, not shipped as opaque SQL.
"""

